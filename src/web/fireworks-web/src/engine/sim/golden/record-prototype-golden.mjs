// Records the golden playback fixture from the PROTOTYPE's own simulation code, so the port's
// golden spec compares against the oracle, not against itself (Phase 2 acceptance 2a.7).
//
//   node src/engine/sim/golden/record-prototype-golden.mjs      (from src/web/fireworks-web)
//
// It slices prototypes/fireworks-prototype.html from `const COLORS = {` up to the Renderer banner
// (model, RNG and simulation: proto l.124-384), unchanged, appends `fire` (proto l.477-484) and
// `shellDuration` (proto l.489),
// runs the scenarios below headless in a fresh module, and writes prototype-golden.ts.
// Re-run it only when the prototype changes; never to make a failing port spec pass.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tmpdir } from 'node:os';
import { mkdtempSync } from 'node:fs';

const here = dirname(fileURLToPath(import.meta.url));
const protoPath = resolve(here, '../../../../../../../prototypes/fireworks-prototype.html');
const html = readFileSync(protoPath, 'utf8');

function slice(from, to) {
  const a = html.indexOf(from);
  const b = html.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`markers not found: ${from} .. ${to}`);
  return html.slice(a, b);
}
const simSource = slice('const COLORS = {', '/* ============================================================\n   Renderer');
const durationSource = slice('function shellDuration(def) {', 'function tick(ticker)');
// The prototype's own fire() (launch counter, base seed and the 7919 stride), so the sequence
// scenario's seeds come from the oracle, not from a constant typed into this harness.
const fireSource = slice('let acc = 0, launchCount = 0', 'function worldWidth()');

// Scenario parameters. The spec repeats these; keep them in step with prototype-golden.spec.ts.
const harness = `
const WORLD_WIDTH = 1280;
const CHECK_STEPS = [60, 240, 360, 450, 600];
function snapshot() {
  const kinds = [0, 0, 0, 0, 0, 0]; let sumX = 0, sumY = 0;
  for (let i = 0; i < P.n; i++) { kinds[P.kind[i]]++; sumX += P.x[i]; sumY += P.y[i]; }
  // Spread: sum of |position - mean| per axis. Sums alone cancel for symmetric bursts, so a
  // radial error (burst speed, drag) can leave them unchanged; the spread cannot hide it.
  const mx = P.n ? sumX / P.n : 0, my = P.n ? sumY / P.n : 0; let devX = 0, devY = 0;
  for (let i = 0; i < P.n; i++) { devX += Math.abs(P.x[i] - mx); devY += Math.abs(P.y[i] - my); }
  return { n: P.n, kinds, sumX: +sumX.toFixed(3), sumY: +sumY.toFixed(3),
    devX: +devX.toFixed(3), devY: +devY.toFixed(3), shells: shells.length };
}
function reset(sky, starBudget) {
  P.n = 0; shells = []; simTime = 0; launchCount = 0; lastLaunch = null;
  world.gravity = sky?.gravity ?? 160; world.wind = sky?.wind ?? 0; world.starBudget = starBudget ?? 1;
}
function runSingle(def, seed, sky, starBudget) {
  reset(sky, starBudget);
  launch(def, WORLD_WIDTH / 2, GROUND - def.burstHeight * GROUND, seed);
  const out = {};
  for (let s = 1; s <= 600; s++) { step(STEP); if (CHECK_STEPS.includes(s)) out[s] = snapshot(); }
  return out;
}
// Every preset fired in turn, one every 30 steps, through the prototype's own fire().
function runSequence() {
  reset();
  const out = {};
  for (let s = 0; s < 900; s++) {
    if (s % 30 === 0 && s / 30 < PRESETS.length) {
      const k = s / 30, def = PRESETS[k];
      fire(def, 100 + k * 110, GROUND - def.burstHeight * GROUND);
    }
    step(STEP);
    if ([60, 240, 360, 450, 600, 900].includes(s + 1)) out[s + 1] = snapshot();
  }
  return out;
}
export const result = {
  presetDefs: PRESETS,
  defaults: { shell: newShell('X'), break: newBreak() },
  colors: COLORS,
  presets: Object.fromEntries(PRESETS.map((p) => [p.name, runSingle(p, 20261112)])),
  sequence: runSequence(),
  windyWillow: runSingle(PRESETS[2], 20261112, { gravity: 220, wind: 40 }),
  halfBudgetTripleBreak: runSingle(PRESETS[9], 20261112, undefined, 0.5),
  shellDuration: Object.fromEntries(PRESETS.map((p) => { reset(); return [p.name, shellDuration(p)]; })),
};
`;

const dir = mkdtempSync(resolve(tmpdir(), 'proto-golden-'));
const modulePath = resolve(dir, 'prototype-sim.mjs');
writeFileSync(modulePath, `${simSource}\n${fireSource}\n${durationSource}\n${harness}`);
const { result } = await import(pathToFileURL(modulePath).href);

const out = resolve(here, 'prototype-golden.ts');
writeFileSync(
  out,
  `// GENERATED by record-prototype-golden.mjs from prototypes/fireworks-prototype.html. Do not edit.\n` +
    `// Values are the prototype's own simulation output (Phase 2 acceptance 2a.7).\n` +
    `/* eslint-disable */\n` +
    `export const PROTOTYPE_GOLDEN = ${JSON.stringify(result)} as const;\n`,
);
// Format in place so a re-run regenerates the checked-in file byte for byte.
const prettier = await import('prettier');
const formatted = await prettier.format(readFileSync(out, 'utf8'), {
  ...(await prettier.resolveConfig(out)),
  filepath: out,
});
writeFileSync(out, formatted);
console.log(`wrote ${out}`);
